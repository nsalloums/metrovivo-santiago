// Frecuencias en segundos entre trenes, por franja horaria y tipo de día.
// wd: lunes-viernes, sa: sábado, su: domingo/festivo. Aproximación basada en
// los rangos publicados por Metro de Santiago.
function freq(peak, valle, low) {
  return {
    wd: [
      ['06:00', '06:30', low],
      ['06:30', '09:00', peak],
      ['09:00', '17:30', valle],
      ['17:30', '20:00', peak],
      ['20:00', '21:30', valle],
      ['21:30', '23:00', low],
    ],
    sa: [
      ['06:30', '21:00', valle],
      ['21:00', '23:00', low],
    ],
    su: [
      ['07:30', '21:00', Math.round(valle * 1.3)],
      ['21:00', '23:00', low],
    ],
  };
}

